<?php

declare(strict_types=1);

namespace Codifyo\TsGeneratorBundle\Generator;

use Codifyo\TsGeneratorBundle\Extractor\MetadataExtractorInterface;
use Codifyo\TsGeneratorBundle\Model\ProjectConfig;
use Codifyo\TsGeneratorBundle\Model\PropertyDefinition;
use Codifyo\TsGeneratorBundle\Model\TypeConfig;
use Codifyo\TsGeneratorBundle\Model\TypeDefinition;
use Codifyo\TsGeneratorBundle\Writer\FileWriter;

final class TypeScriptGenerator implements TypeScriptGeneratorInterface
{
    private const TS_IDENTIFIER_PATTERN = '/^[A-Za-z_$][A-Za-z0-9_$]*$/';

    /** Fallback for referenced classes that cannot be described (unknown class, recursion) */
    private const OPAQUE_TYPE = 'Record<string, any>';

    /**
     * @var array<string, TypeDefinition> Inline definitions cache for the project being generated, keyed by FQCN + groups + mode
     */
    private array $inlineDefinitions = [];

    /**
     * @param array<string, mixed> $projectsConfig
     */
    public function __construct(
        private MetadataExtractorInterface $extractor,
        private FileWriter $fileWriter,
        private array $projectsConfig = [],
    ) {
    }

    public function generate(?string $projectName = null): array
    {
        $projects = $this->parseProjectsConfig();

        if ($projectName !== null && $projectName !== '') {
            if (!isset($projects[$projectName])) {
                throw new \InvalidArgumentException(\sprintf('Project "%s" is not configured.', $projectName));
            }
            $projects = [$projectName => $projects[$projectName]];
        }

        $results = [];

        foreach ($projects as $name => $projectConfig) {
            $results[$name] = $this->generateProject($projectConfig);
        }

        return $results;
    }

    /**
     * @return array<string, ProjectConfig>
     */
    private function parseProjectsConfig(): array
    {
        $parsed = [];

        foreach ($this->projectsConfig as $name => $data) {
            $projectMode = $data['mode'] ?? 'auto';
            $types = [];

            foreach ($data['types'] ?? [] as $typeData) {
                $class = $typeData['class'] ?? '';
                if ($class === '') {
                    continue;
                }

                // The project mode is resolved here so that extractors only depend on TypeConfig
                $typeConfig = new TypeConfig(
                    $class,
                    $typeData['groups'] ?? [],
                    $typeData['name'] ?? null,
                    $typeData['kind'] ?? 'interface',
                    (bool) ($typeData['auto_generate_deps'] ?? false),
                    $typeData['mode'] ?? $projectMode,
                    $typeData['sample_id'] ?? null
                );

                if ($typeConfig->getSampleId() !== null && \in_array($typeConfig->getMode(), ['static', 'jms'], true)) {
                    throw new \InvalidArgumentException(\sprintf('Type "%s" defines a "sample_id" but uses the "%s" mode: samples are only normalized in "runtime" or "auto" mode.', $class, $typeConfig->getMode()));
                }

                $types[] = $typeConfig;
            }

            $parsed[$name] = new ProjectConfig((string) $name, $data['dir'] ?? 'public/ts/types', $types, $projectMode);
        }

        return $parsed;
    }

    /**
     * @return string[] List of written file paths
     */
    private function generateProject(ProjectConfig $projectConfig): array
    {
        $this->inlineDefinitions = [];

        // A declaration is identified by class + groups + name: one class can be exported several times
        /** @var array<string, TypeConfig> $typeConfigs */
        $typeConfigs = [];
        /** @var array<string, list<string>> $keysByClass Declaration keys of each class */
        $keysByClass = [];
        /** @var array<string, true> $autoKeys Declarations created by auto_generate_deps */
        $autoKeys = [];

        foreach ($projectConfig->getTypes() as $typeConfig) {
            $key = $this->declarationKey($typeConfig);
            if (!isset($typeConfigs[$key])) {
                $typeConfigs[$key] = $typeConfig;
                $keysByClass[$typeConfig->getClass()][] = $key;
            }
        }

        $queue = array_keys($typeConfigs);
        /** @var array<string, TypeDefinition> $definitions */
        $definitions = [];

        while ($queue !== []) {
            $key = array_shift($queue);
            $typeConfig = $typeConfigs[$key];
            $definition = $this->extractor->extract($typeConfig);
            $definitions[$key] = $definition;

            if (!$typeConfig->isAutoGenerateDeps()) {
                continue;
            }

            foreach ($definition->getProperties() as $property) {
                foreach ($property->getReferencedClasses() as $targetClass) {
                    if (!class_exists($targetClass) || $this->hasDeclarationFor($targetClass, $typeConfig->getGroups(), $typeConfigs, $keysByClass, $autoKeys)) {
                        continue;
                    }

                    // Already generated with other groups: the new type gets a name derived from its groups
                    $name = isset($keysByClass[$targetClass])
                        ? $this->getShortClassName($targetClass) . $this->groupsSuffix($typeConfig->getGroups())
                        : null;

                    $dependency = new TypeConfig(
                        $targetClass,
                        $typeConfig->getGroups(),
                        $name,
                        $typeConfig->getKind(),
                        true,
                        $typeConfig->getMode()
                    );
                    $dependencyKey = $this->declarationKey($dependency);
                    $typeConfigs[$dependencyKey] = $dependency;
                    $keysByClass[$targetClass][] = $dependencyKey;
                    $autoKeys[$dependencyKey] = true;
                    $queue[] = $dependencyKey;
                }
            }
        }

        $generatedTypeNames = $this->collectGeneratedTypeNames($definitions, $typeConfigs);

        $writtenFiles = [];
        foreach ($definitions as $key => $definition) {
            $content = $this->renderTypeDefinition($definition, $generatedTypeNames, $typeConfigs[$key]);
            $writtenFiles[] = $this->fileWriter->writeFile($projectConfig->getDir(), $definition->getName() . '.ts', $content);
        }

        return $writtenFiles;
    }

    private function declarationKey(TypeConfig $typeConfig): string
    {
        return $typeConfig->getClass() . '|' . implode(',', $this->sortedGroups($typeConfig->getGroups())) . '|' . $typeConfig->getName();
    }

    /**
     * @param string[] $groups
     *
     * @return list<string>
     */
    private function sortedGroups(array $groups): array
    {
        $groups = array_values(array_unique($groups));
        sort($groups);

        return $groups;
    }

    /**
     * A dependency needs no generation when its class is declared explicitly (references then fall back on that
     * declaration) or is already generated with the same groups.
     *
     * @param string[]                    $groups
     * @param array<string, TypeConfig>   $typeConfigs
     * @param array<string, list<string>> $keysByClass
     * @param array<string, true>         $autoKeys
     */
    private function hasDeclarationFor(string $class, array $groups, array $typeConfigs, array $keysByClass, array $autoKeys): bool
    {
        $groups = $this->sortedGroups($groups);

        foreach ($keysByClass[$class] ?? [] as $key) {
            if (!isset($autoKeys[$key]) || $this->sortedGroups($typeConfigs[$key]->getGroups()) === $groups) {
                return true;
            }
        }

        return false;
    }

    /**
     * @param string[] $groups
     */
    private function groupsSuffix(array $groups): string
    {
        $suffix = '';
        foreach ($this->sortedGroups($groups) as $group) {
            foreach (preg_split('/[^A-Za-z0-9]+/', $group, -1, \PREG_SPLIT_NO_EMPTY) ?: [] as $word) {
                $suffix .= ucfirst($word);
            }
        }

        return $suffix;
    }

    /**
     * Validates TS names (they become file names) and detects two declarations mapped to the same name,
     * which would otherwise silently overwrite each other's file.
     *
     * @param array<string, TypeDefinition> $definitions Keyed by declaration key
     * @param array<string, TypeConfig>     $typeConfigs
     *
     * @return array<string, list<array{groups: list<string>, name: string}>> Generated types of each FQCN
     */
    private function collectGeneratedTypeNames(array $definitions, array $typeConfigs): array
    {
        $names = [];
        $declarationsByName = [];

        foreach ($definitions as $key => $definition) {
            $name = $definition->getName();
            $fqcn = $typeConfigs[$key]->getClass();
            $groups = $this->sortedGroups($typeConfigs[$key]->getGroups());
            $label = \sprintf('"%s"%s', $fqcn, $groups === [] ? '' : \sprintf(' (groups: %s)', implode(', ', $groups)));

            if (!preg_match(self::TS_IDENTIFIER_PATTERN, $name)) {
                throw new \InvalidArgumentException(\sprintf('"%s" (class "%s") is not a valid TypeScript identifier.', $name, $fqcn));
            }

            $lowerName = strtolower($name); // case-insensitive file systems
            if (isset($declarationsByName[$lowerName])) {
                throw new \InvalidArgumentException(\sprintf('Declarations %s and %s both generate the TypeScript type "%s". Declare one of them explicitly with a distinct "name" option.', $declarationsByName[$lowerName], $label, $name));
            }

            $declarationsByName[$lowerName] = $label;
            $names[$fqcn][] = ['groups' => $groups, 'name' => $name];
        }

        return $names;
    }

    /**
     * Picks the generated type a property of a parent with the given groups points to: the one declared with the
     * same groups, else the only one declared for the class. Null when the class must be inlined.
     *
     * @param array<string, list<array{groups: list<string>, name: string}>> $generatedTypeNames
     * @param string[]                                                       $parentGroups
     */
    private function findGeneratedName(string $class, array $parentGroups, array $generatedTypeNames): ?string
    {
        $candidates = $generatedTypeNames[$class] ?? [];
        $parentGroups = $this->sortedGroups($parentGroups);

        foreach ($candidates as $candidate) {
            if ($candidate['groups'] === $parentGroups) {
                return $candidate['name'];
            }
        }

        return \count($candidates) === 1 ? $candidates[0]['name'] : null;
    }

    /**
     * @param array<string, list<array{groups: list<string>, name: string}>> $generatedTypeNames Generated types of each FQCN
     */
    private function renderTypeDefinition(TypeDefinition $definition, array $generatedTypeNames, TypeConfig $typeConfig): string
    {
        /** @var array<string, true> $imports */
        $imports = [];
        $propertyLines = [];

        foreach ($definition->getProperties() as $property) {
            $tsType = $this->resolvePropertyType($property, $definition->getClassName(), $generatedTypeNames, $typeConfig, $imports, [$definition->getClassName() => true]);
            $propertyLines[] = '  ' . $this->renderField($property, $tsType) . ';';
        }

        unset($imports[$definition->getName()]);

        $lines = [
            '/* tslint:disable */',
            '/* eslint-disable */',
            '// Auto-generated by CodifyoTsGeneratorBundle. Do not edit manually.',
            '',
        ];

        if ($imports !== []) {
            ksort($imports);
            foreach (array_keys($imports) as $importName) {
                $lines[] = \sprintf("import { %s } from './%s';", $importName, $importName);
            }
            $lines[] = '';
        }

        $lines[] = match ($definition->getKind()) {
            'class' => \sprintf('export class %s {', $definition->getName()),
            'type' => \sprintf('export type %s = {', $definition->getName()),
            default => \sprintf('export interface %s {', $definition->getName()),
        };
        array_push($lines, ...$propertyLines);
        $lines[] = $definition->getKind() === 'type' ? '};' : '}';
        $lines[] = '';

        return implode("\n", $lines);
    }

    /**
     * Replaces the short class names of the property type by their generated TS name, or by an
     * inline description when the class is not generated as a file of its own.
     *
     * @param array<string, list<array{groups: list<string>, name: string}>> $generatedTypeNames
     * @param array<string, true>                                            $imports            Collects the generated types used (passed by reference)
     * @param array<string, true>                                            $visiting           Classes being inlined, to stop on recursive references
     */
    private function resolvePropertyType(
        PropertyDefinition $property,
        string $ownerClass,
        array $generatedTypeNames,
        TypeConfig $typeConfig,
        array &$imports,
        array $visiting,
    ): string {
        $replacements = [];

        foreach ($property->getReferencedClasses() as $refClass) {
            $shortName = $this->getShortClassName($refClass);
            $generatedName = $this->findGeneratedName($refClass, $typeConfig->getGroups(), $generatedTypeNames);

            if ($generatedName !== null) {
                $replacements[$shortName] = $generatedName;
                $imports[$generatedName] = true;
            } elseif (isset($visiting[$refClass]) || $refClass === $ownerClass) {
                $replacements[$shortName] = self::OPAQUE_TYPE;
            } else {
                $replacements[$shortName] = $this->renderInlineClass($refClass, $generatedTypeNames, $typeConfig, $imports, $visiting + [$refClass => true]);
            }
        }

        return $this->replaceIdentifiers($property->getTsType(), $replacements);
    }

    /**
     * Replaces whole identifiers only, in a single pass, so that "User" never matches inside
     * "UserRole" and replacement output is never replaced again. Array-shape keys are left untouched.
     *
     * @param array<string, string> $replacements Map of identifier => replacement
     */
    private function replaceIdentifiers(string $tsType, array $replacements): string
    {
        if ($replacements === []) {
            return $tsType;
        }

        return preg_replace_callback(
            '/(?<![\w$])([A-Za-z_$][\w$]*)(?![\w$])(?!\s*\??\s*:)/',
            static fn (array $m): string => $replacements[$m[1]] ?? $m[1],
            $tsType
        ) ?? $tsType;
    }

    /**
     * Renders the properties of a referenced class inline (e.g. "{ id: number; label: string }"),
     * recursively for its own references.
     *
     * @param array<string, list<array{groups: list<string>, name: string}>> $generatedTypeNames
     * @param array<string, true>                                            $imports
     * @param array<string, true>                                            $visiting
     */
    private function renderInlineClass(string $class, array $generatedTypeNames, TypeConfig $parentTypeConfig, array &$imports, array $visiting): string
    {
        if (!class_exists($class)) {
            return self::OPAQUE_TYPE;
        }

        $inlineTypeConfig = new TypeConfig($class, $parentTypeConfig->getGroups(), null, 'interface', false, $parentTypeConfig->getMode());
        $cacheKey = $class . '|' . implode(',', $inlineTypeConfig->getGroups()) . '|' . $inlineTypeConfig->getMode();
        $definition = $this->inlineDefinitions[$cacheKey] ??= $this->extractor->extract($inlineTypeConfig);

        $fields = [];
        foreach ($definition->getProperties() as $property) {
            $tsType = $this->resolvePropertyType($property, $class, $generatedTypeNames, $inlineTypeConfig, $imports, $visiting);
            $fields[] = $this->renderField($property, $tsType);
        }

        return $fields === [] ? self::OPAQUE_TYPE : '{ ' . implode('; ', $fields) . ' }';
    }

    private function renderField(PropertyDefinition $property, string $tsType): string
    {
        $name = $property->getName();
        if (!preg_match(self::TS_IDENTIFIER_PATTERN, $name)) {
            $name = \sprintf("'%s'", addcslashes($name, "'\\"));
        }

        return $property->isNullable()
            ? \sprintf('%s?: %s | null', $name, $tsType)
            : \sprintf('%s: %s', $name, $tsType);
    }

    private function getShortClassName(string $fqcn): string
    {
        $parts = explode('\\', $fqcn);

        return end($parts);
    }
}
