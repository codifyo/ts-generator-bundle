<?php

declare(strict_types=1);

namespace Codifyo\TsGeneratorBundle\Tests\Helper;

use Codifyo\TsGeneratorBundle\Converter\PhpToTypeScriptTypeConverter;
use Codifyo\TsGeneratorBundle\Extractor\SymfonySerializerRuntimeExtractor;
use Codifyo\TsGeneratorBundle\Generator\TypeScriptGenerator;
use Codifyo\TsGeneratorBundle\Helper\ClassResolver;
use Codifyo\TsGeneratorBundle\Tests\Fixtures\DummyEntityWithGroupedImports;
use Codifyo\TsGeneratorBundle\Tests\Fixtures\DummyEntityWithUseImport;
use Codifyo\TsGeneratorBundle\Tests\Fixtures\DummyTag;
use Codifyo\TsGeneratorBundle\Tests\Fixtures\SubNamespace\DummyImportedEntity;
use Codifyo\TsGeneratorBundle\Tests\Fixtures\SubNamespace\DummyTag as OtherDummyTag;
use Codifyo\TsGeneratorBundle\Writer\FileWriter;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\Component\Serializer\Mapping\Factory\ClassMetadataFactory;
use Symfony\Component\Serializer\Mapping\Loader\AttributeLoader;
use Symfony\Component\Serializer\Normalizer\ObjectNormalizer;
use Symfony\Component\Serializer\Serializer;

class ClassResolverTest extends TestCase
{
    private string $tempDir;

    protected function setUp(): void
    {
        $this->tempDir = sys_get_temp_dir() . '/ts_class_resolver_test_' . uniqid();
    }

    protected function tearDown(): void
    {
        $filesystem = new Filesystem();
        if ($filesystem->exists($this->tempDir)) {
            $filesystem->remove($this->tempDir);
        }
    }

    public function testResolveFqcnWithUseStatement(): void
    {
        $reflection = new \ReflectionClass(DummyEntityWithUseImport::class);
        $resolved = ClassResolver::resolveFqcn('DummyImportedEntity', $reflection);

        $this->assertEquals(DummyImportedEntity::class, $resolved);
    }

    /**
     * @return iterable<string, array{string, string|null}>
     */
    public static function provideNamesUsedByAGroupedImportsFile(): iterable
    {
        yield 'grouped use' => ['DummyImportedEntity', DummyImportedEntity::class];
        yield 'alias inside a group' => ['OtherTag', OtherDummyTag::class];
        yield 'aliased namespace + relative name' => ['Sub\DummyTag', OtherDummyTag::class];
        yield 'same namespace' => ['DummyTag', DummyTag::class];
        yield 'leading backslash FQCN' => ['\\' . DummyTag::class, DummyTag::class];
        yield 'function import is not a class' => ['sprintf', null];
        yield 'unknown name' => ['Unknown', null];
        yield 'empty name' => [' ', null];
    }

    #[DataProvider('provideNamesUsedByAGroupedImportsFile')]
    public function testResolveFqcnWithGroupedAndAliasedImports(string $name, ?string $expected): void
    {
        $this->assertSame($expected, ClassResolver::resolveFqcn($name, new \ReflectionClass(DummyEntityWithGroupedImports::class)));
    }

    public function testAutoGenerateDepsWithCrossNamespaceUseImport(): void
    {
        $classMetadataFactory = new ClassMetadataFactory(new AttributeLoader());
        $normalizer = new ObjectNormalizer($classMetadataFactory);
        $serializer = new Serializer([$normalizer]);

        $converter = new PhpToTypeScriptTypeConverter();
        $extractor = new SymfonySerializerRuntimeExtractor($serializer, null, $converter, $classMetadataFactory);
        $fileWriter = new FileWriter(new Filesystem(), $this->tempDir);

        $projectsConfig = [
            'projet1' => [
                'dir' => $this->tempDir,
                'types' => [
                    [
                        'class' => DummyEntityWithUseImport::class,
                        'groups' => ['serializer_group'],
                        'auto_generate_deps' => true,
                    ],
                ],
            ],
        ];

        $generator = new TypeScriptGenerator($extractor, $fileWriter, $projectsConfig);
        $results = $generator->generate('projet1');

        $this->assertCount(2, $results['projet1']);
        $this->assertFileExists($this->tempDir . '/DummyEntityWithUseImport.ts');
        $this->assertFileExists($this->tempDir . '/DummyImportedEntity.ts');

        $mainContent = file_get_contents($this->tempDir . '/DummyEntityWithUseImport.ts');
        $this->assertStringContainsString("import { DummyImportedEntity } from './DummyImportedEntity';", $mainContent);
        $this->assertStringContainsString('importedItems: Array<DummyImportedEntity>;', $mainContent);
    }
}
